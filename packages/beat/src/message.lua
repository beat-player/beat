-- The messages the app delivers: clicks, what a screen asks for, what a service announces. Each
-- kind is a class with its own `type`, so a message is checked where it is written and a reader
-- sees the fields that kind carries. A message is a table literal; this file only says what each
-- kind holds, and nothing requires it at runtime.
--
-- A new kind is a class below, a row in `beat.Message`, and the handler in the service's `on`
-- table that answers it, whose `message` parameter names the class.
--
-- A plugin with a message of its own writes it with `custom = true`, which is what lets a type
-- the app does not know through the union without letting a misspelt one of the app's own pass.
--- The fields every message may be written with. A message is read by kind, but a plugin's own
--- kind carries whatever it wants, so the base is open; a kind's own class adds the fields it
--- promises and a literal that leaves one out is still an error.
---@class beat.MessageFields: table<string, any>

